import { chromium } from 'playwright';
const b=await chromium.launch({channel:'chrome',headless:true,args:['--no-sandbox']});
const p=await b.newPage({viewport:{width:1200,height:1100}});
const errs=[]; p.on('pageerror',e=>errs.push(String(e?.message||e).slice(0,150)));
await p.goto('http://127.0.0.1:8082',{waitUntil:'load',timeout:45000}); await p.waitForTimeout(2500);
const inp=await p.locator('#app input').all(); await inp[0].fill('admin'); await inp[1].fill('admin');
await p.locator('button:has-text("登录")').first().click(); await p.waitForTimeout(5000);
await p.evaluate(()=>{window.location.hash='#/fcl/operasional/laporanKerja'}); await p.waitForTimeout(2500);
await p.locator('button:has-text("Buat")').first().click(); await p.waitForTimeout(1800);
const m=p.locator('.ant-modal:visible');
const dp=m.locator('.lk-f',{hasText:'TANGGAL LAPORAN'}).locator('.ant-picker input').first();
await dp.click(); await p.waitForTimeout(400);
await p.locator('.ant-picker-cell[title="2026-11-01"]').first().click(); await p.waitForTimeout(1500);
const shiftSel=m.locator('.lk-f',{hasText:'SHIFT LAPORAN'}).locator('.ant-select').first();
await shiftSel.click(); await p.waitForTimeout(300);
await p.locator('.ant-select-item-option',{hasText:'Malam'}).first().click(); await p.waitForTimeout(1500);
console.log('shift laporan:', await shiftSel.innerText());
console.log('notifications:', (await p.locator('.ant-notification-notice').allInnerTexts()).join(' | ').replace(/\s+/g,' ').slice(0,140));
console.log('errors:',errs.length);
await p.screenshot({path:'/tmp/lk_shift_autosync.png'});
await b.close();
